export type IconName = keyof typeof ICONS;

export function icon(name: IconName, className = ''): SVGSVGElement {
  const tpl = document.createElement('template');
  tpl.innerHTML = `<svg class="icon ${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name]}</svg>`;
  return tpl.content.firstElementChild as SVGSVGElement;
}

/** The extension's logo, the same artwork as its toolbar icon. */
export function logo(size: 'sm' | 'lg' = 'sm'): HTMLElement {
  return h('img', { className: `logo logo-${size}`, src: 'icons/icon-128.png', alt: '' });
}

export function kbd(...keys: string[]): HTMLElement {
  const out = h('span', { className: 'keys' });
  keys.forEach((k) => out.append(h('kbd', {}, k)));
  return out;
}

export function plural(n: number, word: string): string {
  return `${n} ${word}${n === 1 ? '' : 's'}`;
}

export function folderName(path: string): string {
  return path.split(/[\\/]/).filter(Boolean).pop() ?? path;
}
